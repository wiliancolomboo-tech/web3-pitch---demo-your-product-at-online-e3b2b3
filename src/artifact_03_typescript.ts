interface AlertPayload {
  level: "INFO" | "WARNING" | "CRITICAL";
  title: string;
  message: string;
  metrics: Record<string, string | number>;
}

export class EnterpriseNotificationHub {
  private resendApiKey?: string;
  private resendFromEmail?: string;
  private resendToEmail?: string;
  private webhookUrl?: string;

  constructor() {
    this.resendApiKey = process.env.RESEND_API_KEY;
    this.resendFromEmail = process.env.RESEND_FROM_EMAIL || "alerts@kronos.security";
    this.resendToEmail = process.env.RESEND_TO_EMAIL;
    this.webhookUrl = process.env.INCIDENT_WEBHOOK_URL;
  }

  public async broadcastAlert(payload: AlertPayload): Promise<void> {
    console.log(`[ALERT DISPATCH] [${payload.level}] ${payload.title}`);

    // 1. Post to Slack/Discord webhook
    if (this.webhookUrl) {
      try {
        await axios.post(this.webhookUrl, {
          username: "Kronos Sentinel Orchestrator",
          avatar_url: "https://raw.githubusercontent.com/solana/solana/master/doc/src/img/solana-logo.png",
          embeds: [
            {
              title: `[${payload.level}] ${payload.title}`,
              description: payload.message,
              color: payload.level === "CRITICAL" ? 15158332 : 3066993,
              fields: Object.entries(payload.metrics).map(([key, value]) => ({
                name: key,
                value: String(value),
                inline: true,
              })),
              timestamp: new Date().toISOString(),
            },
          ],
        });
        console.log(" -> Webhook alert dispatched successfully.");
      } catch (err: any) {
        console.error("Failed to post alert to webhook:", err.message);
      }
    }

    // 2. Deliver high-priority email via Resend
    if (this.resendApiKey && this.resendToEmail) {
      try {
        await axios.post(
          "https://api.resend.com/emails",
          {
            from: this.resendFromEmail,
            to: [this.resendToEmail],
            subject: `[KRONOS ${payload.level}] ${payload.title}`,
            html: `
              <h2>Kronos Autonomous Sentinel Alert</h2>
              <p><strong>Status:</strong> ${payload.level}</p>
              <p>${payload.message}</p>
              <h3>Metrics</h3>
              <pre>${JSON.stringify(payload.metrics, null, 2)}</pre>
              <p><em>Generated by Kronos Node.js Daemon</em></p>
            `,
          },
          {
            headers: {
              Authorization: `Bearer ${this.resendApiKey}`,
              "Content-Type": "application/json",
            },
          }
        );
        console.log(" -> Resend notification email dispatched successfully.");
      } catch (err: any) {
        console.error("Failed to send email via Resend:", err.response?.data || err.message);
      }
    }
  }
}

export class KronosSentinelAgent {
  private connection: Connection;
  private wallet: anchor.Wallet;
  private provider: anchor.AnchorProvider;
  private programId: PublicKey;
  private alerts: EnterpriseNotificationHub;

  constructor(rpcUrl: string, keypairPath: string, programIdStr: string) {
    this.connection = new Connection(rpcUrl, "confirmed");
    const secretKey = JSON.parse(fs.readFileSync(keypairPath, "utf-8"));
    const keypair = Keypair.fromSecretKey(new Uint8Array(secretKey));
    this.wallet = new anchor.Wallet(keypair);
    this.provider = new anchor.AnchorProvider(this.connection, this.wallet, {
      commitment: "confirmed",
    });
    this.programId = new PublicKey(programIdStr);
    this.alerts = new EnterpriseNotificationHub();
  }

  public getSentinelPDA(authority: PublicKey): [PublicKey, number] {
    return PublicKey.findProgramAddressSync(
      [Buffer.from("sentinel_state"), authority.toBuffer()],
      this.programId
    );
  }

  public getVaultPDA(sentinelPDA: PublicKey): [PublicKey, number] {
    return PublicKey.findProgramAddressSync(
      [Buffer.from("sentinel_vault"), sentinelPDA.toBuffer()],
      this.programId
    );
  }

  public async runKeeperLoop(
    authority: PublicKey,
    reserveRecipient: PublicKey,
    simulatedLossBps: number,
    rebalanceLamports: number
  ) {
    const [sentinelPDA] = this.getSentinelPDA(authority);
    const [vaultPDA] = this.getVaultPDA(sentinelPDA);

    console.log(`Starting Kronos Keeper daemon for Sentinel: ${sentinelPDA.toBase58()}`);
    console.log(`Linked Vault PDA: ${vaultPDA.toBase58()}`);

    const idlPath = "./target/idl/kronos_sentinel.json";
    if (!fs.existsSync(idlPath)) {
      throw new Error(`IDL not found at ${idlPath}. Run 'anchor build' first.`);
    }
    const idl = JSON.parse(fs.readFileSync(idlPath, "utf8"));
    const program = new Program(idl, this.provider);

    try {
      console.log(`Assessing volatility conditions... Detected loss: ${simulatedLossBps} bps`);

      // Invoke trigger_rebalance instruction
      const tx = await program.methods
        .triggerRebalance(simulatedLossBps, new anchor.BN(rebalanceLamports))
        .accounts({
          sentinel: sentinelPDA,
          vault: vaultPDA,
          reserveDestination: reserveRecipient,
          keeper: this.wallet.publicKey,
          systemProgram: SystemProgram.programId,
        })
        .rpc();

      console.log(`Rebalance successfully executed! Signature: ${tx}`);

      const vaultBalance = await this.connection.getBalance(vaultPDA);

      await this.alerts.broadcastAlert({
        level: "WARNING",
        title: "Autonomous Treasury Rebalance Executed",
        message: `Kronos Sentinel successfully intervened to safeguard capital.`,
        metrics: {
          txSignature: tx,
          simulatedLossBps,
          rebalancedLamports: rebalanceLamports,
          remainingVaultBalanceLamports: vaultBalance,
        },
      });
    } catch (error: any) {
      console.error("Rebalance execution rejected or failed:", error.message);
      await this.alerts.broadcastAlert({
        level: "CRITICAL",
        title: "Keeper Execution Anomaly",
        message: `Autonomous execution failed: ${error.message}`,
        metrics: {
          error: error.message,
          timestamp: Date.now(),
        },
      });
    }
  }
}

