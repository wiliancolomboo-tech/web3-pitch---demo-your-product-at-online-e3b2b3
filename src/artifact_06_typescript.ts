import { Connection, PublicKey, clusterApiUrl } from "@solana/web3.js";
import axios from "axios";
import * as dotenv from "dotenv";

dotenv.config();

export interface WebhookConfig {
  slackWebhookUrl?: string;
  discordWebhookUrl?: string;
  resendApiKey?: string;
  notificationEmail?: string;
}

export class AegisEnterpriseNotifier {
  private config: WebhookConfig;

  constructor(config: WebhookConfig) {
    this.config = config;
  }

  async broadcastEvent(eventName: string, details: Record<string, any>): Promise<void> {
    const timestamp = new Date().toISOString();
    const payload = {
      source: "AegisPay Solana Protocol Engine",
      event: eventName,
      timestamp,
      data: details,
    };

    console.log(`[AEGIS-TELEMETRY] [${timestamp}] Emitting: ${eventName}`, details);

    // 1. Dispatch to Slack Webhook
    if (this.config.slackWebhookUrl) {
      try {
        await axios.post(this.config.slackWebhookUrl, {
          text: `🚨 *[AegisPay Alert]*: *${eventName}*\n\`\`\`json\n${JSON.stringify(details, null, 2)}\n\`\`\``,
        });
      } catch (err: any) {
        console.error(`[TELEMETRY-ERROR] Slack dispatch failed:`, err.message);
      }
    }

    // 2. Dispatch to Discord Webhook
    if (this.config.discordWebhookUrl) {
      try {
        await axios.post(this.config.discordWebhookUrl, {
          embeds: [
            {
              title: `⚡ AegisPay On-Chain Event: ${eventName}`,
              color: 0x14f195, // Solana Emerald
              fields: Object.entries(details).map(([k, v]) => ({
                name: k,
                value: String(v),
                inline: true,
              })),
              footer: { text: "Solana Mainnet/Devnet Sentinel Daemon" },
              timestamp,
            },
          ],
        });
      } catch (err: any) {
        console.error(`[TELEMETRY-ERROR] Discord dispatch failed:`, err.message);
      }
    }

    // 3. Dispatch to Resend Institutional Email
    if (this.config.resendApiKey && this.config.notificationEmail) {
      try {
        await axios.post(
          "https://api.resend.com/emails",
          {
            from: "ops@aegispay.io",
            to: this.config.notificationEmail,
            subject: `[AegisPay Event] ${eventName} - Escrow ID #${details.escrow_id || "N/A"}`,
            html: `
              <h2>AegisPay Escrow Notification</h2>
              <p>An on-chain state transition was confirmed on the Solana Network:</p>
              <ul>
                ${Object.entries(details)
                  .map(([k, v]) => `<li><strong>${k}:</strong> ${v}</li>`)
                  .join("")}
              </ul>
              <hr/>
              <small>Automated audit record generated by Aegis Sentinel.</small>
            `,
          },
          {
            headers: {
              Authorization: `Bearer ${this.config.resendApiKey}`,
              "Content-Type": "application/json",
            },
          }
        );
      } catch (err: any) {
        console.error(`[TELEMETRY-ERROR] Resend dispatch failed:`, err.message);
      }
    }
  }
}

export async function runEscrowListener() {
  const rpcUrl = process.env.SOLANA_RPC_URL || clusterApiUrl("devnet");
  const programId = new PublicKey(
    process.env.PROGRAM_ID || "AegisPay11111111111111111111111111111111111"
  );
  const connection = new Connection(rpcUrl, "confirmed");

  const notifier = new AegisEnterpriseNotifier({
    slackWebhookUrl: process.env.SLACK_WEBHOOK_URL,
    discordWebhookUrl: process.env.DISCORD_WEBHOOK_URL,
    resendApiKey: process.env.RESEND_API_KEY,
    notificationEmail: process.env.NOTIFICATION_EMAIL,
  });

  console.log(`[AEGIS-AGENT] Connected to Solana RPC: ${rpcUrl}`);
  console.log(`[AEGIS-AGENT] Subscribing to Program: ${programId.toBase58()}`);

  connection.onLogs(
    programId,
    async (logsInfo) => {
      const logs = logsInfo.logs;
      const signature = logsInfo.signature;

      for (const log of logs) {
        if (log.includes("Instruction: InitializeEscrow")) {
          await notifier.broadcastEvent("EscrowInitialized", { signature });
        } else if (log.includes("Instruction: SubmitMilestone")) {
          await notifier.broadcastEvent("MilestoneSubmitted", { signature });
        } else if (log.includes("Instruction: ApproveMilestone")) {
          await notifier.broadcastEvent("MilestoneApproved", { signature });
        } else if (log.includes("Instruction: DisputeEscrow")) {
          await notifier.broadcastEvent("EscrowDisputed", { signature });
        } else if (log.includes("Instruction: ResolveDispute")) {
          await notifier.broadcastEvent("DisputeResolved", { signature });
        }
      }
    },
    "confirmed"
  );
}

if (require.main === module) {
  runEscrowListener().catch((err) => {
    console.error("[FATAL] Agent crashed:", err);
    process.exit(1);
  });
}